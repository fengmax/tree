function shuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    const t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
}

/* 从指定情绪里取一条：洗牌袋队列，一轮内不重复 */
function pickReply(category) {
  const list = (REPLY_BANK[category] && REPLY_BANK[category].length)
    ? REPLY_BANK[category]
    : REPLY_BANK.default;
  const state = getState();
  const bag = (state.replyBag && typeof state.replyBag === 'object') ? state.replyBag : {};
  // 过滤掉非法索引：文案库日后增删时，旧队列能自愈
  let queue = (Array.isArray(bag[category]) ? bag[category] : [])
    .filter(i => Number.isInteger(i) && i >= 0 && i < list.length);
  if (!queue.length) queue = shuffle(list.map((_, i) => i));
  const idx = queue.shift();
  bag[category] = queue;
  setState({ replyBag: bag });
  return list[idx] || list[0];
}

/* 输入一句话 → 树的回应 */
export function replyFor(text) {
  const input = String(text || '');
  let top = -1;
  let hits = [];
  for (let i = 0; i < PATTERNS.length; i += 1) {
    const cat = PATTERNS[i][0];
    if (!PATTERNS[i][1].test(input)) continue;
    const p = PRIORITY[cat] || 0;
    if (p > top) { top = p; hits = [cat]; }
    else if (p === top) hits.push(cat);
  }
  const category = hits.length ? hits[Math.floor(Math.random() * hits.length)] : 'default';
  return pickReply(category);
}
